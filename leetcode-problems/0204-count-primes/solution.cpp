    int32_t floorSqrt(int32_t x) {
        int32_t r = (int32_t)sqrt(x - 1);
        while (r * r <= x)
            r++;
        return (r - 1);
    }

    int32_t floorCbrt(int32_t x) {
        int32_t r = (int32_t)cbrt(x - 1);
        while (r * r * r <= x)
            r++;
        return (r - 1);
    }

    int32_t phi(int32_t x, int32_t s) {
        if (s == 0)
            return x;
        if (s <= M)
            return partOfPhi[x % primeProduct[s]][s] +
                   (x / primeProduct[s]) * partOfPhi[primeProduct[s]][s];
        if (x <= prime[s] * prime[s])
            return pi[x] - s + 1;
        if (x <= prime[s] * prime[s] * prime[s] && x < N) {
            int32_t s2x = pi[floorSqrt(x)];
            int32_t ans = pi[x] - (s2x + s - 2) * (s2x - s + 1) / 2;
            for (int32_t i = s + 1; i <= s2x; ++i)
                ans += pi[x / prime[i]];
            return ans;
        }
        return phi(x, s - 1) - phi(x / prime[s], s - 1);
    }

    int32_t primePi(int32_t x) {
        if (x <= 1)
            return 0;
        if (x < N)
            return (int32_t)pi[(int16_t)x];
        int32_t a = primePi(floorSqrt(floorSqrt(x)));
        int32_t b = primePi(floorSqrt(x));
        int32_t c = primePi(floorCbrt(x));
        int32_t sum = phi(x, a) + (b + a - 2) * (b - a + 1) / 2;
        for (int32_t i = a + 1; i <= b; i++) {
            int32_t w = x / prime[i];
            sum -= primePi(w);
            if (i > c)
                continue;
            int32_t limit = primePi(floorSqrt(w));
            for (int32_t j = i; j <= limit; j++)
                sum -= primePi(w / prime[j]) - (j - 1);
        }
        return sum;
    }
